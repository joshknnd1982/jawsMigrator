"""Set up the private NVDA's settings for the tests of version 1.56 (issue 49): the tester's profiles, and a silent copy of
Eloquence64RS 19.1.4's driver. Test tooling, never shipped.

    python setup_issue49.py            the tester's profiles, the question about speech settings that differ is not asked
    python setup_issue49.py ask        the same, and the question is asked 20 seconds after NVDA starts
    python setup_issue49.py off        as the first, with the assistant's setting that keeps the voice's settings the same
                                       everywhere turned off: NVDA and Eloquence as the tester had them

The profiles are what NVDA's log shows the tester's as it loaded them (nvda.ini, JAWS - msedge.ini, browseMode.ini, ...). The
voice is "eloquence": Eloquence64RS's functions that keep and apply a copy of the voice's settings for each set of turned-on
profiles, and its SynthDriver's methods that load and save settings and set the pitch and volume, are the add-on's own, word for
word (tests/issue49Sources.py has them and says where from), so a real NVDA's profile switches, Settings dialog and settings ring
run into them as they do into the real driver. The engine is a table of numbers and the voice makes no sound, so nothing here
can be heard on the PC it runs on.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import issue49Sources  # noqa: E402

CFG = os.path.join(HERE, "cfg")


def write(path, text):
	os.makedirs(os.path.dirname(path), exist_ok=True)
	with open(path, "w", encoding="utf-8", newline="\r\n") as stream:
		stream.write(text)


