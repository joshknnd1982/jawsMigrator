def main():
	ask = "ask" in sys.argv[1:]
	off = "off" in sys.argv[1:]
	with open(os.path.join(HERE, "nvda.ini.sample"), encoding="utf-8") as stream:
		sample = stream.read()
	start = sample.index("[speech]")
	end = sample.index("[braille]")
	ini = sample[:start] + NVDA_INI_SPEECH + sample[end:]
	ini = ini.replace("\tsoundVolume = 0\n", "\tsoundVolume = 0\n\taudioDuckingMode = 0\n")
	write(os.path.join(CFG, "nvda.ini"), ini)
	for name, text in PROFILES.items():
		write(os.path.join(CFG, "profiles", name + ".ini"), text)
	write(os.path.join(CFG, "profileTriggers.ini"), TRIGGERS)
	write(os.path.join(CFG, "scratchpad", "synthDrivers", "eloquence.py"), DRIVER.format(profiles=issue49Sources.ELOQUENCE_PROFILES, methods=issue49Sources.ELOQUENCE_DRIVER_METHODS))
	state = {"welcomeShown": True, "checkForUpdatesAutomatically": False}
	if not ask:
		# The question that is asked once for these values: said to have been asked.
		state["evenSpeechAsked"] = ["eloquence.volume:JAWS - msedge=80|browseMode=100|normal configuration=100"]
	if off:
		state["keepSpeechEven"] = False
	write(os.path.join(CFG, "jawsMigrator", "state.json"), json.dumps(state, indent="\t"))
	os.makedirs(os.path.join(CFG, "scratchpad", "globalPlugins"), exist_ok=True)
	driver = os.path.join(CFG, "scratchpad", "globalPlugins", "aa47driver.py")
	with open(os.path.join(HERE, "aa47driver.py"), "rb") as source, open(driver, "wb") as target:
		target.write(source.read())
	print("set up", CFG, "(the question is asked)" if ask else "(the question is not asked)", "(kept the same everywhere: off)" if off else "")


if __name__ == "__main__":
	main()
